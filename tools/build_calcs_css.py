#!/usr/bin/env python3
"""Write site/assets/calcs.css: the calculator styles for the three division pages.

The division pages (galvanizing, wire-drawing, reinplast) do not load assets/item.css, and their own colour tokens
mean other things (their --ink is a light colour), so a calculator placed on them needs its own sheet:
  1. a token block and the shared classes the calculator uses (.k .btn .fld .u), scoped to .cx-app, and
  2. every .cx rule of item.css, copied as it is (":root[data-brand=rein]" becomes "#app[data-brand=rein]").
site.js puts the sheet in front of v39.css, so the contrast fixes in v39.css still win.

    python3 tools/build_calcs_css.py            # write site/assets/calcs.css
    python3 tools/build_calcs_css.py --check    # exit 1 when calcs.css no longer matches item.css

Run it after changing any .cx rule in item.css. tools/check_site.py runs the check.
"""
